import assert from 'node:assert/strict';
import {ensurePartyFolders} from '../module/data/party-folders.mjs';
import {readFileSync} from 'node:fs';
const SYSTEM='fast-nri-v14';
const folder=(data)=>({...data,getFlag(scope,key){return this.flags?.[scope]?.[key];}});
const contents=[folder({type:'Actor',name:'Партия'}),folder({type:'Item',flags:{[SYSTEM]:{partyFolder:'archive'}}})];
const calls=[];
const ru=JSON.parse(readFileSync(new URL('../lang/ru.json',import.meta.url)));
const en=JSON.parse(readFileSync(new URL('../lang/en.json',import.meta.url)));
globalThis.game={user:{isActiveGM:false},folders:{contents,documentClass:{async createDocuments(rows){calls.push(structuredClone(rows));const created=rows.map(folder);contents.push(...created);return created;}}},i18n:{localize(key){return key.split('.').reduce((obj,k)=>obj[k],ru);}}};
assert.deepEqual(await ensurePartyFolders(),[]);
assert.equal(calls.length,0);
game.user.isActiveGM=true;
const created=await ensurePartyFolders();
assert.equal(created.length,2);
assert.deepEqual(calls[0].map(x=>[x.name,x.type,x.folder,x.sorting,x.flags[SYSTEM].partyFolder]),[['Партия','Actor',null,'m','party'],['Архив персонажей','Actor',null,'m','archive']]);
assert.equal(contents[0].name,'Партия');
assert.equal(contents[0].flags,undefined,'do not adopt a user folder by name');
created[0].name='Renamed';
created[0].folder='some-parent';
assert.deepEqual(await ensurePartyFolders(),[],'renaming/moving does not recreate folder');
assert.equal(calls.length,1);
contents.splice(contents.indexOf(created[1]),1);
game.i18n.localize=key=>key.split('.').reduce((obj,k)=>obj[k],en);
const restored=await ensurePartyFolders();
assert.equal(restored.length,1);
assert.equal(restored[0].name,'Character Archive');
assert.equal(restored[0].getFlag(SYSTEM,'partyFolder'),'archive');
assert.equal(created[0].name,'Renamed');
assert.deepEqual(await ensurePartyFolders(),[]);
assert.equal(calls.length,2);
assert.equal(contents.filter(f=>f.type==='Actor'&&f.getFlag(SYSTEM,'partyFolder')==='party').length,1);
assert.equal(contents.filter(f=>f.type==='Actor'&&f.getFlag(SYSTEM,'partyFolder')==='archive').length,1);
console.log('Party folders: active GM, native creation, stable roles, repeat startup, missing folder, localization PASS');
