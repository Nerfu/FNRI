import assert from 'node:assert/strict';
import {skillFormulaDisplay} from '../module/sheets/skill-formula-display.mjs';
import {skillFormula} from '../module/rolls/checks.mjs';
import {prepareRoll} from '../module/rolls/roll-context.mjs';
globalThis.game={i18n:{localize:k=>k},settings:{get:()=> 'strict'}};
const id='core_acrobatics';
const base={id,dice:'1d6',modifier:0};
const item=(name,parts)=>({uuid:`Item.${name}`,name,system:{mechanics:{rollContributions:parts.map(p=>({kinds:['skill'],skillId:id,applyToOtherRolls:true,...p}))}}});
const bonus=(value,more={})=>({kind:'modifier',value,...more});
const effect=(name,changes=[],rule=null)=>({uuid:`ActiveEffect.${name}`,name,active:true,system:{changes},flags:{'fast-nri-v14':{...(rule?{rollInfluence:{kinds:['skill'],skillId:id,...rule}}:{})}}});
const actor={type:'character',system:{skills:{[id]:{...base}}},items:{contents:[]},effects:{contents:[]}};
const display=(raw=base,prepared=actor.system.skills[id],opts={})=>skillFormulaDisplay(raw,prepared,actor,opts);
assert.equal(display().text,'d6');
actor.items.contents=[item('Первый',[bonus('1d6')]),item('Второй',[bonus('1d6'),bonus(2)]),item('Опциональный',[bonus('1d12',{defaultEnabled:false})])];
assert.equal(display().text,'d6+2d6+2');assert.match(display().hint,/Первый/);assert.match(display().hint,/Второй/);assert.doesNotMatch(display().hint,/Опциональный/);
// Same engine produces two distinct d6 bonus terms. Grouping is display-only.
const roll=await prepareRoll({actor,kind:'skill',skillId:id,formula:skillFormula(base),skipDialog:true});
assert.equal(roll.expression,'1d20 + (1d6) + (1d6) + (1d6) + (2)');
actor.items.contents=[item('Малый',[bonus('1d4',{nonStackingGroup:'equipmentBonus'})]),item('Большой',[bonus('1d8',{nonStackingGroup:'equipmentBonus'})])];
assert.equal(display().text,'d6+1d8');
actor.items.contents=[];
actor.effects.contents=[effect('Состояние',[{key:`system.skills.${id}.modifier`,type:'add',value:2}]),effect('Усиление',[{key:`system.skills.${id}.dice`,type:'override',value:'1d8'}])];
actor.system.skills[id]={...base,dice:'1d8+1d4',modifier:2};
assert.equal(display().text,'d8+1d4+2');assert.equal(display().arrow,'↑');assert.match(display().hint,/Состояние/);assert.match(display().hint,/Усиление/);
actor.system.skills[id]={...base,dice:'1d4',modifier:-2};assert.equal(display().text,'d4−2');assert.equal(display().arrow,'↓');
actor.system.skills[id]={...base};assert.equal(display().arrow,'');assert.match(display().hint,/Усиление/);
actor.effects.contents=[];
actor.items.contents=[item('Дополнение',[bonus('1d6'),bonus('-1d6')])];assert.equal(display().text,'d6+1d6−1d6');
actor.items.contents=[item('Повышение',[{kind:'replacement',from:'1d6',to:'1d8'}]),item('Понижение',[{kind:'replacement',from:'1d8',to:'1d6'}])];assert.equal(display().text,'d6');assert.equal(display().arrow,'');assert.match(display().hint,/Повышение/);assert.match(display().hint,/Понижение/);
actor.items.contents=[];
actor.effects.contents=[effect('Одноразовый',[],{modifier:'1d12',onUse:'remove'})];assert.equal(display().text,'d6');
actor.effects.contents=[];
assert.equal(display({id,dice:'',modifier:0},{dice:'1d6',modifier:0}).text,'1d6');assert.equal(display({id,dice:'',modifier:0},{dice:'',modifier:0}).text,'—');
assert.equal(display({id,dice:'2*(1d6+1d8)',modifier:0},{dice:'2*(1d6+1d8)',modifier:3}).text,'2*(1d6+1d8)+3');
assert.equal(display({id,dice:'1d8',modifier:0},{dice:'1d8',modifier:0},{originalFace:6,origin:'Продвинутый'}).arrow,'↑');
assert.equal(actor.system.skills[id].dice,'1d6');
console.log('PASS effective skill formula, real default roll engine, native no duplication, non-stacking, sources, signed dice and steps');
