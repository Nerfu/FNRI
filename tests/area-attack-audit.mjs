import assert from 'node:assert/strict';
import {areaCheckState,resolveAreaResults,latestAreaDamageReport} from '../module/damage/area-attack.mjs';
import {applyRollCorrection,nativeRollView} from '../module/damage/roll-editor.mjs';
import {areaInterventionChoices} from '../module/damage/area-card-interventions.mjs';
const ID='fast-nri-v14',messages=[];
const actor={uuid:'Actor.shared',isOwner:true,documentName:'Actor',items:{contents:[]}};
const token=id=>({name:'Гоблин',actor,document:{uuid:`Scene.s.Token.${id}`,actor}});
const a=token('a'),b=token('b');
const doc=(id,flags,rolls=[])=>{const m={id,rolls,flags:{[ID]:flags},getFlag(s,k){return this.flags[s]?.[k]},async update(patch){for(const [path,value] of Object.entries(patch))this.flags[ID][path.split('.').at(-1)]=structuredClone(value);}};messages.push(m);return m;};
globalThis.game={user:{id:'gm',isGM:true},messages:{contents:messages,get:id=>messages.find(m=>m.id===id)},i18n:{localize:k=>k}};
const part=(id,value)=>({id,kind:'die',faces:6,formula:'1d6',value,original:value});
const row=(t,initialDegree)=>({key:t.document.uuid,uuid:t.document.uuid,name:t.name,initialDegree});
const roll={total:12,dice:[{faces:20,number:1,results:[{result:12,active:true}]}]};
const card={version:2,revision:0,originalAttackTotal:12,attackTotal:12,naturalD20:12,targetDefense:'ac',parts:[part('a',2),part('b',4),part('c',6)],areaAttack:{version:1,attackTotal:12,naturalD20:12,targets:[row(a,'great'),row(b,'success')]}};
const root=doc('root',{weaponDamage:card},[roll]);
assert.deepEqual(resolveAreaResults(root).map(r=>r.damage),[12,10]);
assert.deepEqual(resolveAreaResults(root,[{targetKey:a.document.uuid,success:true,kindKey:'dodge',safe:true}]).map(r=>r.damage),[4,10]);
assert.deepEqual(resolveAreaResults(root,[{targetKey:b.document.uuid,success:true,naturalD20:20}]).map(r=>r.damage),[12,0]);
assert.deepEqual(card.parts.map(p=>p.value),[2,4,6]);
assert.equal(areaInterventionChoices(actor,{targetDefense:'ac'}).some(c=>c.kind==='counteraction'),false);
assert.equal(areaInterventionChoices(actor,{targetDefense:'reflex'}).some(c=>c.kind==='counteraction'),true);
await applyRollCorrection(nativeRollView(root,0),{partId:'offset',action:'set',value:4});
assert.deepEqual(areaCheckState(root),{total:16,changed:true});
assert.deepEqual(resolveAreaResults(root).map(r=>r.degree),[null,null]);
assert.equal(root.rolls[0].total,12);
assert.equal(card.areaAttack.targets[0].initialDegree,'great');
await applyRollCorrection(nativeRollView(root,0),{partId:'offset',action:'set',value:0});
assert.deepEqual(resolveAreaResults(root).map(r=>r.damage),[12,10]);
assert.deepEqual(resolveAreaResults(root,[{targetKey:a.document.uuid,success:true,attackCheckTotal:16}]).map(r=>r.degree),[null,'success']);
await applyRollCorrection(nativeRollView(root,0),{partId:'die-1',action:'set',value:20});
await applyRollCorrection(nativeRollView(root,0),{partId:'offset',action:'set',value:-8});
assert.deepEqual(areaCheckState(root),{total:12,changed:true});
assert.deepEqual(resolveAreaResults(root).map(r=>r.degree),[null,null]);
const receipt=(id,t,extra={})=>doc(id,{hpReport:{version:1,kind:'damage',actorUuid:actor.uuid,tokenUuid:t.document.uuid,sourceMessageId:root.id,sourceRevision:0,...extra}});
assert.equal(latestAreaDamageReport(root,b),null);
const ra=receipt('ra',a),rb=receipt('rb',b);
receipt('reverted',a,{reverted:true});receipt('stale',b,{sourceRevision:1});
assert.equal(latestAreaDamageReport(root,a),ra);
assert.equal(latestAreaDamageReport(root,b),rb);
console.log('PASS P.3.3 area: shared dice, independent targets/defenses, corrected check manual resolution, exact token HP receipts');
