import assert from 'node:assert/strict';
import {readFileSync,readdirSync} from 'node:fs';
import {CLASSES} from '../module/data/classes.mjs';
import {appendCombatDice,combatDamageReferences,combatDamageEntries,relativeOffGuard} from '../module/rolls/combat-dice-damage.mjs';
import {preparedDamageDefinitions,applyDirectRollModifiers} from '../module/rolls/roll-context.mjs';
const dir=new URL('../packs/_source/abilities/',import.meta.url);
const cards=readdirSync(dir).filter(f=>f.startsWith('rogue-')).map(f=>JSON.parse(readFileSync(new URL(f,dir),'utf8')));
const S='fast-nri-v14';
assert.equal(cards.length,8);assert.deepEqual(new Set(cards.map(c=>c.flags[S].contentId)),new Set(CLASSES.rogue.abilityIds));
assert.equal(appendCombatDice('1d20 + 1d6','d6',2),'1d20 + 1d6 + 2d6');
assert.equal(appendCombatDice('1d20 + 1d6 + 2','d6',1),'1d20 + 1d6 + 2');
const roll={dice:[{faces:20,results:[{result:14}]},{faces:6,results:[{result:4}]},{faces:6,results:[{result:5},{result:2}]},{faces:6,results:[{result:6}]}]};
const refs=combatDamageReferences(roll,'1d20 + 1d6 + 2d6',{selected:[]});
assert.deepEqual(refs.map(r=>r.value),[4,5,2]);
assert.deepEqual(combatDamageEntries({combatDamageReferences:refs},'partial'),[]);
const entries=combatDamageEntries({combatDamageReferences:refs},'great',{components:[{id:'die-2',value:3},{id:'die-3',excluded:true}]});
assert.deepEqual(entries[0].parts.map(p=>p.value),['3','2']);
const base=[{id:'A',kind:'die',faces:6,formula:'1d6'}];
const context={selected:entries,manual:[],expression:applyDirectRollModifiers('1d6',entries)};
assert.deepEqual(preparedDamageDefinitions(base,context).slice(1).map(p=>[p.kind,p.value]),[['fixed',3],['fixed',2]]);
const plan=cards.find(c=>c.name==='Коварный план'), weakness=cards.find(c=>c.name==='Чутьё на слабость');
const owner={items:{contents:[{...plan,effects:{contents:[{uuid:'Actor.r.Item.plan.ActiveEffect.a'}]}}]}};
const enemy={actor:{effects:{contents:[{origin:'Actor.r.Item.plan.ActiveEffect.a',flags:{[S]:{relativeOffGuard:true}}}]}}};
assert.equal(relativeOffGuard(owner,enemy),true);assert.equal(relativeOffGuard({items:{contents:[]}},enemy),false);
enemy.actor.effects.contents[0].disabled=true;assert.equal(relativeOffGuard(owner,enemy),false);
const grid={isSquare:true,size:100};
const token=(id,x,side,hp)=>({document:{uuid:id,parent:{id:'scene'},x,y:0,width:1,height:1,disposition:side},actor:{system:{hp:{current:hp}},effects:{contents:[]}}});
const target=token('t',0,-1,10),ally=token('a',100,-1,10),other=token('o',100,1,10);
const rogue={items:{contents:[weakness]}};
assert.equal(relativeOffGuard(rogue,target,{tokens:[target,other],grid}),true);
assert.equal(relativeOffGuard(rogue,target,{tokens:[target,ally],grid}),false);
ally.actor.system.hp.current=0;assert.equal(relativeOffGuard(rogue,target,{tokens:[target,ally],grid}),true);
globalThis.foundry={documents:{Combatant:class{_getInitiativeFormula(){return '1d20'}}}};
const {initiativeContribution}=await import('../module/combat/initiative.mjs');
assert.equal(initiativeContribution({actor:{system:{className:'Разбойник'},items:{contents:[cards.find(c=>c.name==='Мгновенная реакция')]}}}),2);
console.log('PASS Rogue: eight cards, combat dice references, degree, edited results, fixed damage, relative effects, isolation and initiative');
