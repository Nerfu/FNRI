import assert from 'node:assert/strict';
import {rollEditorPage,renderRollEditorContent,saveRollEditorInput,ROLL_EDITOR_PAGE_SIZE} from '../module/damage/roll-editor.mjs';
const ID='fast-nri-v14';
globalThis.game={user:{isGM:true,id:'gm'},i18n:{localize:k=>k.split('.').at(-1)}};
const parts=Array.from({length:603},(_,i)=>({id:`die-${i}`,kind:'die',faces:i%2?8:6,
  formula:i%2?'1d8':'1d6',value:2,original:2,excluded:false}));
const card={version:2,parts,adjustments:{penalty:0,resistance:0,vulnerability:0},history:[],naturalD20:12};
const msg={flags:{[ID]:{weaponDamage:card}},getFlag(s,k){return this.flags[s][k];},
  canUserModify(){return true;},async update(patch){for(const [k,v] of Object.entries(patch))this.flags[ID][k.split('.').at(-1)]=v;}};
const raw=renderRollEditorContent(msg);
assert.equal((raw.match(/fnri-editor-part-row/g)??[]).length,ROLL_EDITOR_PAGE_SIZE);
assert.match(raw,/\#1 · 1d6/);
assert.match(raw,/data-fnri-editor-nav="next"/);
assert.doesNotMatch(raw,/data-fnri-editor-op="reroll:20"/);
assert.doesNotMatch(raw,/<select/);
assert.match(raw,/name="intervention"/);
assert.match(raw,/name="critical"/);
assert.equal(rollEditorPage(parts,{page:30}).items.length,3);
const last=renderRollEditorContent(msg,{page:30});
assert.match(last,/#601 · 1d6/);
assert.match(last,/data-fnri-editor-op="reroll:602"/);
assert.doesNotMatch(last,/data-fnri-editor-nav="next"/);
assert.match(last,/data-fnri-editor-nav="prev"/);
assert.equal(rollEditorPage(parts,{page:99}).page,30,'past-end pages clamp');
const exact=renderRollEditorContent(msg,{query:'#500',page:0,interventionDraft:true,criticalDraft:true});
assert.equal((exact.match(/fnri-editor-part-row/g)??[]).length,1);
assert.match(exact,/#500 · 1d8/);
assert.match(exact,/data-fnri-editor-op="set:499"/,'filter still targets original part index');
assert.match(exact,/name="intervention" value="true" checked/,'navigation keeps unsaved flag draft');
assert.match(exact,/name="critical" value="true" checked/,'navigation keeps unsaved critical draft');
const search=rollEditorPage(parts,{query:'1d8',page:9});
assert.equal(search.count,301);
assert.equal(search.items[0].index,361,'pagination offsets use original positions');
const empty=renderRollEditorContent(msg,{query:'9d1000'});
assert.match(empty,/editorNoResults/);
assert.doesNotMatch(empty,/data-fnri-editor-nav="next"/);
await saveRollEditorInput(msg,{operation:'set:499',partValue_499:5});
assert.equal(msg.getFlag(ID,'weaponDamage').parts[499].value,5);
assert.equal(msg.getFlag(ID,'weaponDamage').parts[498].value,2);
assert.equal(msg.getFlag(ID,'weaponDamage').parts[500].value,2);
assert.equal(msg.getFlag(ID,'weaponDamage').parts[499].original,2);
console.log('PASS: 603 independent dice, 20-row pages, search, original indexes, preserved flag draft and targeted correction');
